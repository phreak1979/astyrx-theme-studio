import { generateThemeTs, themeIdentifier, themeIdentifierBase, buildTokenMap, type ExportInput } from './astryx';
import { stringifyThemeJson } from './json';

export interface ExportFile {
  name: string;
  content: string;
  mime: string;
}

export function generateReadme(input: ExportInput): string {
  const id = input.meta.id;
  const ident = themeIdentifier(id);
  const file = `${themeIdentifierBase(id)}Theme`;
  return `# ${input.meta.name}

Astryx theme generated by Astryx Theme Studio${input.astryxVersion ? ` for \`@astryxdesign/core\` ${input.astryxVersion}` : ''}.
${input.meta.description ? `\n${input.meta.description}\n` : ''}
## Add it to your app

1. Copy \`${file}.ts\` into your project (for example \`src/theme/\`).
2. Pass it to Astryx's \`Theme\` provider:

\`\`\`tsx
import { Theme } from '@astryxdesign/core/theme';
import { ${ident} } from './theme/${file}';

<Theme theme={${ident}}>
  <App />
</Theme>
\`\`\`

3. For production you can pre-build the CSS so no runtime style injection is needed:

\`\`\`bash
npx @astryxdesign/cli theme build src/theme/${file}.ts
\`\`\`

## Files

- \`${file}.ts\`: the theme (${Object.keys(buildTokenMap(input)).length} tokens, scope: ${input.scope}).
- \`${id}.theme.json\`: Theme Studio backup. Re-import it in Theme Studio to keep editing.
- \`metadata.json\`: name, id, Astryx version and timestamps.
`;
}

export function buildExportPackage(input: ExportInput): ExportFile[] {
  const file = `${themeIdentifierBase(input.meta.id)}Theme`;
  return [
    { name: `${file}.ts`, content: generateThemeTs(input), mime: 'text/typescript' },
    { name: `${input.meta.id}.theme.json`, content: stringifyThemeJson(input), mime: 'application/json' },
    {
      name: 'metadata.json',
      content:
        JSON.stringify(
          {
            name: input.meta.name,
            id: input.meta.id,
            description: input.meta.description,
            author: input.meta.author,
            astryxVersion: input.astryxVersion,
            tokens: Object.keys(buildTokenMap(input)).length,
            scope: input.scope,
            createdAt: input.meta.createdAt,
            updatedAt: input.meta.updatedAt,
          },
          null,
          2,
        ) + '\n',
      mime: 'application/json',
    },
    { name: 'README.md', content: generateReadme(input), mime: 'text/markdown' },
  ];
}
