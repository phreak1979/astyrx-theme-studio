import { formatLightDark, sameValue } from '../core/css-value';
import type { Pair, ThemeMeta } from '../core/theme-state';
import type { TokenRegistry } from '../core/token-registry';
import { themeImportPath } from '../core/version';

export type ExportScope = 'modified' | 'complete';
export type ThemeTokenValue = string | [light: string, dark: string];

export interface ExportInput {
  registry: TokenRegistry;
  overrides: Readonly<Record<string, Pair>>;
  getWorking: (token: string) => Pair | undefined;
  meta: ThemeMeta;
  astryxVersion: string | null;
  scope: ExportScope;
}

export function buildTokenMap(input: ExportInput): Record<string, ThemeTokenValue> {
  const out: Record<string, ThemeTokenValue> = {};
  const names = input.scope === 'complete' ? input.registry.entries.map((e) => e.name) : Object.keys(input.overrides);
  for (const name of names) {
    const entry = input.registry.byName.get(name);
    const pair = input.getWorking(name);
    if (!entry || !pair) continue;
    out[name] = entry.modeSpecific && !sameValue(pair.light, pair.dark) ? [pair.light, pair.dark] : pair.light;
  }
  return out;
}

export function jsString(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\r?\n/g, ' ')}'`;
}

/** `dream-score-theme` -> `dreamScore` (the exporter appends `Theme`). */
export function themeIdentifierBase(id: string): string {
  const stripped = id.replace(/-theme$/, '') || id;
  const camel = stripped.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  return /^[a-z_$]/i.test(camel) ? camel : `theme${camel}`;
}

export function themeIdentifier(id: string): string {
  return `${themeIdentifierBase(id)}Theme`;
}

function comment(text: string): string {
  return text.replace(/\*\//g, '* /').replace(/\r?\n/g, ' ');
}

export function generateThemeTs(input: ExportInput): string {
  const tokens = buildTokenMap(input);
  const lines: string[] = [];
  const { meta } = input;
  const header = [
    `Generated by Astryx Theme Studio${input.astryxVersion ? ` for @astryxdesign/core ${input.astryxVersion}` : ''}.`,
    meta.description && comment(meta.description),
    meta.author && `Author: ${comment(meta.author)}`,
    input.scope === 'complete' ? 'Contains the complete resolved token set.' : 'Contains modified tokens only; everything else inherits the Astryx defaults.',
  ].filter(Boolean) as string[];

  lines.push('/**', ...header.map((h) => ` * ${h}`), ' */');
  lines.push(`import { defineTheme } from '${themeImportPath(input.astryxVersion)}';`, '');
  lines.push(`export const ${themeIdentifier(meta.id)} = defineTheme({`);
  lines.push(`  name: ${jsString(meta.id)},`);
  lines.push('  tokens: {');
  for (const [name, value] of Object.entries(tokens)) {
    lines.push(`    ${jsString(name)}: ${Array.isArray(value) ? `[${jsString(value[0])}, ${jsString(value[1])}]` : jsString(value)},`);
  }
  lines.push('  },', '});', '');
  return lines.join('\n');
}

/** CSS equivalent, handy for quick pasting; not the primary export format. */
export function generateCssVariables(input: ExportInput): string {
  const body = Object.entries(input.overrides)
    .map(([t, p]) => `  ${t}: ${formatLightDark(p.light, p.dark)};`)
    .join('\n');
  return `:root {\n${body}\n}\n`;
}
