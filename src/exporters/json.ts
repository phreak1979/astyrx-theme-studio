import { sameValue } from '../core/css-value';
import type { Pair, ThemeMeta } from '../core/theme-state';
import type { TokenRegistry } from '../core/token-registry';
import { validateValue } from '../core/validators';
import type { ExportInput } from './astryx';

export const JSON_SCHEMA_VERSION = 1;

export interface ThemeStudioJson {
  schemaVersion: number;
  generator: 'astryx-theme-studio';
  astryxVersion: string | null;
  name: string;
  id: string;
  description: string;
  author: string;
  createdAt: string;
  updatedAt: string;
  scope: 'modified' | 'complete';
  light: Record<string, string>;
  dark: Record<string, string>;
}

export function buildThemeJson(input: ExportInput): ThemeStudioJson {
  const names = input.scope === 'complete' ? input.registry.entries.map((e) => e.name) : Object.keys(input.overrides);
  const light: Record<string, string> = {};
  const dark: Record<string, string> = {};
  for (const n of names) {
    const p = input.getWorking(n);
    if (!p || !input.registry.byName.has(n)) continue;
    light[n] = p.light;
    dark[n] = p.dark;
  }
  const { meta } = input;
  return {
    schemaVersion: JSON_SCHEMA_VERSION,
    generator: 'astryx-theme-studio',
    astryxVersion: input.astryxVersion,
    name: meta.name,
    id: meta.id,
    description: meta.description,
    author: meta.author,
    createdAt: meta.createdAt,
    updatedAt: meta.updatedAt,
    scope: input.scope,
    light,
    dark,
  };
}

export function stringifyThemeJson(input: ExportInput): string {
  return JSON.stringify(buildThemeJson(input), null, 2) + '\n';
}

export interface ParsedImport {
  ok: boolean;
  errors: string[];
  warnings: string[];
  duplicates: string[];
  overrides: Record<string, Pair>;
  meta?: Partial<ThemeMeta>;
  astryxVersion?: string | null;
}

/** Return the source text of the object assigned to `"key"`, or null. */
function objectText(text: string, key: string): string | null {
  const m = new RegExp(`"${key}"\\s*:\\s*\\{`).exec(text);
  if (!m) return null;
  let i = m.index + m[0].length;
  const start = i;
  let depth = 1;
  let inStr = false;
  for (; i < text.length && depth > 0; i++) {
    const c = text[i];
    if (inStr) {
      if (c === '\\') i++;
      else if (c === '"') inStr = false;
    } else if (c === '"') inStr = true;
    else if (c === '{') depth++;
    else if (c === '}') depth--;
  }
  return text.slice(start, i - 1);
}

function findDuplicates(text: string): string[] {
  const dups = new Set<string>();
  for (const side of ['light', 'dark']) {
    const body = objectText(text, side);
    if (!body) continue;
    const seen = new Set<string>();
    const re = /"(--[^"]+)"\s*:/g;
    let m: RegExpExecArray | null;
    while ((m = re.exec(body))) {
      if (seen.has(m[1]!)) dups.add(m[1]!);
      seen.add(m[1]!);
    }
  }
  return [...dups];
}

export function parseThemeJson(text: string, registry: TokenRegistry): ParsedImport {
  const res: ParsedImport = { ok: false, errors: [], warnings: [], duplicates: [], overrides: {} };
  let data: unknown;
  try {
    data = JSON.parse(text);
  } catch (e) {
    res.errors.push(`Not valid JSON: ${(e as Error).message}`);
    return res;
  }
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    res.errors.push('Expected a Theme Studio JSON object.');
    return res;
  }
  const d = data as Partial<ThemeStudioJson>;
  if (d.generator !== 'astryx-theme-studio') res.errors.push('File was not generated by Astryx Theme Studio.');
  if (d.schemaVersion !== JSON_SCHEMA_VERSION) res.errors.push(`Unsupported schemaVersion ${String(d.schemaVersion)} (expected ${JSON_SCHEMA_VERSION}).`);
  if (!d.light || typeof d.light !== 'object' || !d.dark || typeof d.dark !== 'object') {
    res.errors.push('Both "light" and "dark" token maps are required.');
  }
  if (res.errors.length) return res;

  res.duplicates = findDuplicates(text);
  if (res.duplicates.length) res.errors.push(`Duplicate token definitions: ${res.duplicates.join(', ')}.`);

  const light = d.light as Record<string, unknown>;
  const dark = d.dark as Record<string, unknown>;
  const names = new Set([...Object.keys(light), ...Object.keys(dark)]);
  for (const name of names) {
    const entry = registry.byName.get(name);
    if (!entry) {
      res.errors.push(`Unknown token ${name}.`);
      continue;
    }
    const l = light[name];
    const dk = dark[name];
    if (typeof l !== 'string' || typeof dk !== 'string') {
      res.errors.push(`${name} must have string light and dark values.`);
      continue;
    }
    const lr = validateValue(entry.type, l, entry.enumValues);
    const dr = validateValue(entry.type, dk, entry.enumValues);
    if (!lr.ok) res.errors.push(`${name} (light): ${lr.error}`);
    if (!dr.ok) res.errors.push(`${name} (dark): ${dr.error}`);
    if (!entry.modeSpecific && !sameValue(l, dk)) res.errors.push(`${name} does not support different light and dark values.`);
    res.overrides[name] = { light: l.trim(), dark: dk.trim() };
  }

  if (d.astryxVersion && registry.astryxVersion && d.astryxVersion !== registry.astryxVersion) {
    res.warnings.push(`File was created for Astryx ${d.astryxVersion}; installed is ${registry.astryxVersion}.`);
  }
  res.astryxVersion = d.astryxVersion ?? null;
  res.meta = {
    name: typeof d.name === 'string' ? d.name : undefined,
    id: typeof d.id === 'string' ? d.id : undefined,
    description: typeof d.description === 'string' ? d.description : '',
    author: typeof d.author === 'string' ? d.author : '',
  };
  res.ok = res.errors.length === 0;
  return res;
}

export interface DiffRow {
  token: string;
  status: 'added' | 'changed' | 'removed';
  current: Pair;
  next: Pair;
}

/** Compare effective working values: what the app shows now vs after applying the import. */
export function diffImport(
  currentOverrides: Readonly<Record<string, Pair>>,
  imported: Readonly<Record<string, Pair>>,
  getOriginal: (token: string) => Pair | undefined,
): DiffRow[] {
  const rows: DiffRow[] = [];
  const tokens = new Set([...Object.keys(currentOverrides), ...Object.keys(imported)]);
  for (const token of tokens) {
    const orig = getOriginal(token);
    if (!orig) continue;
    const cur = currentOverrides[token] ?? orig;
    const nxt = imported[token] ?? orig;
    if (sameValue(cur.light, nxt.light) && sameValue(cur.dark, nxt.dark)) continue;
    const status: DiffRow['status'] = !(token in currentOverrides) ? 'added' : !(token in imported) ? 'removed' : 'changed';
    rows.push({ token, status, current: cur, next: nxt });
  }
  return rows.sort((a, b) => a.token.localeCompare(b.token));
}

